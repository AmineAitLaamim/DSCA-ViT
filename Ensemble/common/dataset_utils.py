# ============================================================
# Ensemble — dataset_utils (split loading + dataset creation)
# ============================================================
#
# Validation (default runs): load split_indices_wsi.npz, use
#   val_indices to select the 810 held-out images from train_dir.
#
# Official test (--eval-test only): load test_dir DIRECTLY as a
#   full dataset — do NOT index it with test_indices. This is
#   because test_indices is known to be the identity mapping
#   [0,1,...,N-1] over test_dir images, so both are identical.
#   A permanent guard asserts this identity so a future split
#   regeneration is caught immediately.
#
# Per-model transforms: each constituent model needs its OWN
#   dataset transform (vit_ce/vit_corn normalize, uni_ce does
#   not), so build_eval_dataset() is model-aware. When TTA is
#   enabled the dataset is built with transform=None so the TTA
#   wrapper can re-transform the raw PIL image per augmentation.
# ============================================================

from __future__ import annotations

import numpy as np
from pathlib import Path
from torch.utils.data import Dataset, Subset

from datasets.dataset import HER2Dataset
from .transforms import get_model_transform


def load_split(split_indices_path: str):
    """Load val_indices and assert test_indices is the identity mapping.

    Returns (val_indices, test_indices).
    """
    path = Path(split_indices_path)
    if not path.exists():
        raise FileNotFoundError(
            f"Split file not found at '{path}'. This file must already "
            "exist; it is never regenerated by the ensemble package."
        )
    data = np.load(path)
    for key in ("train_indices", "val_indices", "test_indices"):
        if key not in data:
            raise KeyError(f"Split file '{path}' is missing key '{key}'.")
    val_indices = data["val_indices"]
    test_indices = data["test_indices"]

    # Permanent guard: the official test set is loaded directly from
    # test_dir (not indexed by test_indices). This is only valid if
    # test_indices is the identity mapping, which was verified on
    # Toubkal. Raise immediately if that ever stops holding.
    identity = np.array_equal(
        test_indices, np.arange(len(test_indices), dtype=test_indices.dtype)
    )
    print(
        f"  [split] test_indices identity mapping over "
        f"{len(test_indices)} images: {identity}"
    )
    if not identity:
        raise ValueError(
            "test_indices is NOT the identity mapping. The direct "
            "test_dir-loading assumption no longer holds; update the "
            "loader before continuing."
        )
    return val_indices, test_indices


def build_eval_dataset(
    root_dir: str, indices, model_name: str, tta: bool, image_size: int = 224
) -> Dataset:
    """Build a dataset for ONE model with its own (per-model) transform.

    When tta=True the transform is None so the TTA wrapper can apply
    each augmentation to the raw PIL image. When tta=False the single
    per-model transform is applied directly.
    Returns:
      - val: Subset(HER2Dataset(train_dir), val_indices)
      - test: HER2Dataset(test_dir) loaded directly (indices=None)
    """
    transform = None if tta else get_model_transform(model_name, image_size=image_size)
    full = HER2Dataset(root_dir=root_dir, transform=transform)
    if indices is not None:
        ds = Subset(full, indices.tolist())
    else:
        ds = full
    kind = "val" if indices is not None else "test"
    print(
        f"  [data] {kind} dataset for '{model_name}': {len(ds)} images "
        f"(tta={tta})"
    )
    return ds
